export const BLIND_BANDS = Object.freeze(Object.keys(BLIND_PRICE_BANDS));

export function validateBlindPriceTable() {
  return BLIND_WIDTHS.length === 16 && BLIND_BANDS.every((band) => {
    const table = BLIND_PRICE_BANDS[band];
    return table.prices.length === table.drops.length
      && table.prices.every((row) => row.length === BLIND_WIDTHS.length);
  });
}

if (!validateBlindPriceTable()) throw new Error("Invalid blind price table dimensions.");
